import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC_ENTRY = path.join(ROOT, 'src', 'index.js');
const DIST_DIR = path.join(ROOT, 'dist');
const DIST_FILE = path.join(DIST_DIR, 'tavern-language.js');

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const visited = new Map();

function normalizeId(absPath) {
  return path.relative(ROOT, absPath).replace(/\\/g, '/');
}

function transformModule(code, absPath) {
  const dir = path.dirname(absPath);
  const deps = [];

  // 1. 转换 side-effect import: import './foo.js';
  let out = code.replace(
    /^\s*import\s+['"]([^'"]+)['"]\s*;?\s*$/gm,
    (_, spec) => {
      const target = path.resolve(dir, spec);
      deps.push(target);
      return `__req(${JSON.stringify(normalizeId(target))});`;
    }
  );

  // 2. 转换 named import: import { a, b as c } from './foo.js';
  out = out.replace(
    /^\s*import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"]\s*;?\s*$/gm,
    (_, names, spec) => {
      const target = path.resolve(dir, spec);
      deps.push(target);
      const destructured = names
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .map((item) => {
          const m = item.match(/^(\w+)\s+as\s+(\w+)$/);
          return m ? `${m[1]}: ${m[2]}` : item;
        })
        .join(', ');
      return `const { ${destructured} } = __req(${JSON.stringify(normalizeId(target))});`;
    }
  );

  // 3. 收集导出声明
  const exportedNames = [];

  out = out.replace(
    /^\s*export\s+(async\s+)?function\s+(\w+)/gm,
    (_, asyncKw = '', name) => {
      exportedNames.push([name, name]);
      return `${asyncKw}function ${name}`;
    }
  );

  out = out.replace(
    /^\s*export\s+(const|let|var)\s+(\w+)/gm,
    (_, kind, name) => {
      exportedNames.push([name, name]);
      return `${kind} ${name}`;
    }
  );

  // 4. 转换块级 export { a, b as c };
  out = out.replace(
    /^\s*export\s+\{([^}]+)\}\s*;?\s*$/gm,
    (_, names) => {
      const lines = names
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .map((item) => {
          const m = item.match(/^(\w+)\s+as\s+(\w+)$/);
          const local = m ? m[1] : item;
          const exported = m ? m[2] : item;
          return `exports.${exported} = ${local};`;
        });
      return lines.join('\n');
    }
  );

  if (exportedNames.length > 0) {
    out += '\n' + exportedNames.map(([local, exp]) => `exports.${exp} = ${local};`).join('\n');
  }

  return { out, deps };
}

function collect(absPath) {
  const id = normalizeId(absPath);
  if (visited.has(id)) return;
  visited.set(id, null);

  const raw = fs.readFileSync(absPath, 'utf8');
  const { out, deps } = transformModule(raw, absPath);
  for (const dep of deps) {
    collect(dep);
  }
  visited.set(id, out);
}

collect(SRC_ENTRY);

const moduleEntries = [...visited.entries()]
  .map(
    ([id, body]) =>
      `  ${JSON.stringify(id)}: function(exports, __req) {\n${body
        .split('\n')
        .map((l) => '    ' + l)
        .join('\n')}\n  }`
  )
  .join(',\n');

const bundle = `/**
 * Tavern Language v${pkg.version}
 * SillyTavern 酒馆助手沉浸式外语学习插件
 * Repo: https://github.com/cone97218-alt/language
 * Auto-generated by scripts/build.mjs — Do not edit dist/ directly.
 */
const __modules = {
${moduleEntries}
};

const __cache = {};
function __req(id) {
  if (__cache[id]) return __cache[id].exports;
  const mod = { exports: {} };
  __cache[id] = mod;
  if (!__modules[id]) {
    throw new Error('[TavernLanguage] 找不到模块: ' + id);
  }
  __modules[id](mod.exports, __req);
  return mod.exports;
}

const __entry = __req('src/index.js');

export const init = __entry.init;
export const destroy = __entry.destroy;
export const version = __entry.version;
export const registerLanguage = __entry.registerLanguage;
export const registerDictionary = __entry.registerDictionary;
export const registerTranslator = __entry.registerTranslator;
export const openSettings = __entry.openSettings;

if (typeof window !== 'undefined') {
  window.__TAVERN_LANG_MODULE__ = __entry;
}
`;

fs.mkdirSync(DIST_DIR, { recursive: true });
fs.writeFileSync(DIST_FILE, bundle, 'utf8');
console.log(`[build] 已打包 ${visited.size} 个模块 -> ${normalizeId(DIST_FILE)} (${(bundle.length / 1024).toFixed(1)} KB)`);
